package com.varshith.queueless;

import android.os.Bundle;
import android.util.Log;
import android.view.View;

import androidx.activity.EdgeToEdge;
import androidx.appcompat.app.AppCompatActivity;
import androidx.core.content.ContextCompat;
import androidx.core.graphics.Insets;
import androidx.core.view.ViewCompat;
import androidx.core.view.WindowInsetsCompat;
import androidx.credentials.Credential;
import androidx.credentials.CredentialManager;
import androidx.credentials.CredentialManagerCallback;
import androidx.credentials.GetCredentialRequest;
import androidx.credentials.GetCredentialResponse;
import androidx.credentials.exceptions.GetCredentialException;
import androidx.fragment.app.Fragment;
import androidx.fragment.app.FragmentManager;

import com.google.android.libraries.identity.googleid.GetGoogleIdOption;
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential;
import com.google.android.material.snackbar.Snackbar;
import com.varshith.queueless.data.QueueRepository;
import com.varshith.queueless.databinding.ActivityMainBinding;
import com.varshith.queueless.ui.HistoryFragment;
import com.varshith.queueless.ui.HomeFragment;
import com.varshith.queueless.ui.MyQueuesFragment;


/**
 * Single-activity app. Shows a Google sign-in gate until a user is signed in,
 * then owns the bottom navigation and the fragment back stack:
 * - showTab()   swaps the three root tabs (Queues / My Queues / History)
 * - pushFragment() puts a detail screen (queue detail, admin screens) on top
 *   of the current tab; the system back button pops it.
 *
 * <p>The user's role is NOT decided here — it is read from {@code users/{uid}}
 * in Firestore by the screens themselves.</p>
 */
public class MainActivity extends AppCompatActivity {

    private static final String TAG = "QueueLess";

    /** Generated by the google-services plugin from the web OAuth client. */
    private static final String WEB_CLIENT_ID_RES = "default_web_client_id";

    private ActivityMainBinding binding;
    private QueueRepository repo;
    private CredentialManager credentialManager;
    private boolean signingIn = false;

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        binding = ActivityMainBinding.inflate(getLayoutInflater());
        setContentView(binding.getRoot());

        repo = QueueRepository.getInstance();
        credentialManager = CredentialManager.create(this);

        // Edge-to-edge: draw behind the system bars, pad top/left/right of the
        // content and pad the bottom navigation so it clears the gesture bar.
        EdgeToEdge.enable(this);
        ViewCompat.setOnApplyWindowInsetsListener(binding.getRoot(), (v, insets) -> {
            Insets bars = insets.getInsets(WindowInsetsCompat.Type.systemBars());
            binding.getRoot().setPadding(bars.left, bars.top, bars.right, 0);
            binding.bottomNav.setPadding(0, 0, 0, bars.bottom);
            return insets;
        });

        binding.btnSignIn.setOnClickListener(v -> beginGoogleSignIn());

        // Bottom navigation switches between the three root tabs.
        binding.bottomNav.setOnItemSelectedListener(item -> {
            showTab(rootTabFor(item.getItemId()));
            return true;
        });

        // Tapping the already-selected tab pops any detail screen back to the root.
        binding.bottomNav.setOnItemReselectedListener(item -> showTab(rootTabFor(item.getItemId())));

        updateAuthUi();
        maybeShowHome();
    }

    // ------------------------------------------------------------------- auth

    /** Show the sign-in gate or the app shell, depending on the current user. */
    public void updateAuthUi() {
        boolean signedIn = repo.currentUserId() != null;
        binding.signInGroup.setVisibility(signedIn ? View.GONE : View.VISIBLE);
        binding.fragmentContainer.setVisibility(signedIn ? View.VISIBLE : View.GONE);
        binding.bottomNav.setVisibility(signedIn ? View.VISIBLE : View.GONE);
    }

    /** Put Home on screen when signed in and nothing is showing yet. */
    private void maybeShowHome() {
        if (repo.currentUserId() == null) {
            return;
        }
        if (getSupportFragmentManager().findFragmentById(R.id.fragment_container) != null) {
            return;
        }
        showTab(new HomeFragment());
    }

    /** Sign out and drop every screen so their listeners stop. */
    public void signOut() {
        repo.signOut();
        FragmentManager fm = getSupportFragmentManager();
        fm.popBackStackImmediate(null, FragmentManager.POP_BACK_STACK_INCLUSIVE);
        Fragment current = fm.findFragmentById(R.id.fragment_container);
        if (current != null) {
            fm.beginTransaction().remove(current).commitNow();
        }
        updateAuthUi();
    }

    private void beginGoogleSignIn() {
        if (signingIn) {
            return;
        }
        String webClientId = resolveWebClientId();
        if (webClientId == null) {
            Snackbar.make(binding.getRoot(), R.string.sign_in_not_configured,
                    Snackbar.LENGTH_LONG).show();
            return;
        }

        signingIn = true;
        GetGoogleIdOption googleIdOption = new GetGoogleIdOption.Builder()
                .setFilterByAuthorizedAccounts(false)
                .setServerClientId(webClientId)
                .setAutoSelectEnabled(false)
                .build();
        GetCredentialRequest request = new GetCredentialRequest.Builder()
                .addCredentialOption(googleIdOption)
                .build();

        credentialManager.getCredentialAsync(this, request, null,
                ContextCompat.getMainExecutor(this),
                new CredentialManagerCallback<GetCredentialResponse, GetCredentialException>() {
                    @Override
                    public void onResult(GetCredentialResponse result) {
                        signingIn = false;
                        handleGoogleResult(result);
                    }

                    @Override
                    public void onError(GetCredentialException e) {
                        signingIn = false;
                        Log.e(TAG, "Google sign-in cancelled or failed", e);
                        Snackbar.make(binding.getRoot(), R.string.sign_in_failed,
                                Snackbar.LENGTH_LONG).show();
                    }
                });
    }

    private void handleGoogleResult(GetCredentialResponse result) {
        Credential credential = result.getCredential();
        if (!GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL.equals(credential.getType())) {
            Snackbar.make(binding.getRoot(), R.string.sign_in_failed, Snackbar.LENGTH_LONG).show();
            return;
        }
        GoogleIdTokenCredential googleCredential;
        try {
            googleCredential = GoogleIdTokenCredential.createFrom(credential.getData());
        } catch (Exception e) {
            Log.e(TAG, "Malformed Google ID token", e);
            Snackbar.make(binding.getRoot(), R.string.sign_in_failed, Snackbar.LENGTH_LONG).show();
            return;
        }

        repo.signInWithGoogle(googleCredential.getIdToken(), new QueueRepository.Callback<String>() {
            @Override
            public void onSuccess(String userId) {
                Log.d(TAG, "Signed in: " + userId);
                updateAuthUi();
                maybeShowHome();
            }

            @Override
            public void onError(Exception e) {
                Log.e(TAG, "Firebase sign-in failed", e);
                Snackbar.make(binding.getRoot(), R.string.sign_in_failed, Snackbar.LENGTH_LONG).show();
            }
        });
    }

    /**
     * The web OAuth client id the google-services plugin turns into
     * {@code R.string.default_web_client_id}. Looked up by name so the project
     * still builds before the Google provider is configured in Firebase.
     */
    private String resolveWebClientId() {
        int id = getResources().getIdentifier(WEB_CLIENT_ID_RES, "string", getPackageName());
        if (id == 0) {
            return null;
        }
        String value = getString(id);
        return (value == null || value.trim().isEmpty()) ? null : value.trim();
    }

    // -------------------------------------------------------------- navigation

    /** Replace the container with a root tab, clearing any pushed detail screens. */
    public void showTab(Fragment fragment) {
        FragmentManager fm = getSupportFragmentManager();
        fm.popBackStackImmediate(null, FragmentManager.POP_BACK_STACK_INCLUSIVE);
        fm.beginTransaction()
                .replace(R.id.fragment_container, fragment)
                .commit();
    }

    /** Push a screen on top of the current tab (queue detail, admin screens). */
    public void pushFragment(Fragment fragment) {
        getSupportFragmentManager().beginTransaction()
                .replace(R.id.fragment_container, fragment)
                .addToBackStack(null)
                .commit();
    }

    private Fragment rootTabFor(int menuItemId) {
        if (menuItemId == R.id.nav_my_queues) return new MyQueuesFragment();
        if (menuItemId == R.id.nav_history) return new HistoryFragment();
        return new HomeFragment();
    }
}
